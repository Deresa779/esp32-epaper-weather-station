# -*- coding: utf-8 -*-
"""
Generates the Chinese bitmap font for the e-paper weather station.

Input : the Han characters to display (see CHARS)
Output: src/fontCN_zh.c - fully compatible with Waveshare's CH_CN / cFONT structs

Bitmap spec: Source Han Serif SC Bold, 32x32 pixels per glyph, 1bpp,
row-major, MSB first.
CH_CN.matrix has a fixed length of MAX_HEIGHT_FONT*MAX_WIDTH_FONT/8 = 164 bytes;
this script uses the first 32*32/8 = 128 bytes and pads the rest with 0.

To add glyphs : append them to CHARS and re-run this script.
To change font : edit FONT_PATH and adjust W/H to the bitmap size that suits it best.
"""
from PIL import Image, ImageDraw, ImageFont
import sys

# The Windows console is not UTF-8 by default, so printing Chinese directly
# would raise a UnicodeEncodeError.
if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')

CHARS = "未来天气星期一二三四五六日"

# 32px is the balanced choice: Source Han Serif Bold smears its horizontal
# strokes at 24px, and only at 32px does the thin-horizontal/thick-vertical
# contrast actually show. Going larger (40px) makes the 4-character title 160px
# wide, which would collide with the temperature box on the right.
W, H = 32, 32                       # Bitmap width and height per glyph
FONT_PATH = "tools/fonts/SourceHanSerifSC-Bold.otf"
FONT_INDEX = 0                      # Single-weight OTF, index is always 0
SLOT = 41 * 32 // 8                 # 164, the fixed length of CH_CN.matrix
OUT = "src/fontCN_zh.c"


def pick_font(draw, ch):
    """Tries font sizes from large to small; returns the first that fits without clipping."""
    for size in range(H, 8, -1):
        font = ImageFont.truetype(FONT_PATH, size, index=FONT_INDEX)
        bbox = draw.textbbox((0, 0), ch, font=font)
        if bbox[2] - bbox[0] <= W and bbox[3] - bbox[1] <= H:
            return font, bbox
    raise RuntimeError("无法为 %r 找到合适字号" % ch)


def render(ch):
    """Renders one Han character as a 32x32 1bpp bitmap; returns a byte list (128 bytes)."""
    img = Image.new("1", (W, H), 0)
    draw = ImageDraw.Draw(img)
    font, bbox = pick_font(draw, ch)
    w, h = bbox[2] - bbox[0], bbox[3] - bbox[1]
    x = (W - w) // 2 - bbox[0]
    y = (H - h) // 2 - bbox[1]
    draw.text((x, y), ch, font=font, fill=1)

    px = img.load()
    out = []
    for row in range(H):
        for cb in range(W // 8):
            b = 0
            for bit in range(8):
                if px[cb * 8 + bit, row]:
                    b |= 0x80 >> bit
            out.append(b)
    assert len(out) == W // 8 * H
    return out


def main():
    lines = [
        '#include "fonts.h"',
        '',
        '// This file is auto-generated by tools/gen_fontcn.py - do not edit by hand.',
        '// Spec: Source Han Serif Bold, 32x32 pixels per glyph, 1bpp, row-major, MSB first.',
        '// Glyphs included: %s' % CHARS,
        '',
        'const CH_CN FontCN_zh_Table[] = {',
    ]

    for ch in CHARS:
        data = render(ch)
        full = data + [0x00] * (SLOT - len(data))
        lines.append('/*--  Character: %s  --*/' % ch)
        lines.append('{"%s",' % ch)
        for i in range(0, len(full), 16):
            lines.append('  ' + ','.join('0x%02X' % b for b in full[i:i + 16]) + ',')
        lines.append('},')

    lines += [
        '};',
        '',
        'cFONT FontCN_zh = {',
        '  FontCN_zh_Table,',
        '  sizeof(FontCN_zh_Table)/sizeof(CH_CN),  /* size of table */',
        '  16,  /* ASCII Width */',
        '  32,  /* Width  */',
        '  32,  /* Height */',
        '};',
        '',
    ]

    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))

    print('已生成 %s：%d 个字（%s）' % (OUT, len(CHARS), CHARS))

    # Also dump an ASCII-art preview so the glyph shapes can be eyeballed.
    for ch in CHARS:
        data = render(ch)
        rows = []
        for row in range(H):
            line = ''
            for bit in range(W):
                byte = data[row * 3 + bit // 8]
                line += '#' if byte & (0x80 >> (bit % 8)) else '.'
            rows.append(line)
        print('\n[%s]' % ch)
        print('\n'.join(rows))


if __name__ == '__main__':
    main()
