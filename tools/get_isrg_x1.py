# -*- coding: utf-8 -*-
"""
Extracts ISRG Root X1 from the local certifi bundle, verifies its SHA-256
fingerprint, then generates src/certs.h.

Why look it up by fingerprint rather than by label: certifi's comment labels can
change, a fingerprint cannot. Let's Encrypt's published ISRG Root X1 SHA-256
fingerprint is hardcoded below; if it does not match we abort with an error.
Better to fail loudly than to flash a wrong certificate into the firmware.

To regenerate (after a certificate rotation or a certifi upgrade):
    python tools/get_isrg_x1.py
"""
import base64
import hashlib
import os
import sys

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')

OUT = "src/certs.h"
LABEL = "ISRG Root X1"
EXPECT_SHA256 = ("96:BC:EC:06:26:49:76:F3:74:60:77:9A:CF:28:C5:A7:"
                 "CF:E8:A3:C0:AA:E1:1A:8F:FC:EE:05:C0:BD:DF:08:C6")
HUGE = 65537


def find_bundle():
    try:
        import certifi
        return certifi.where()
    except ImportError:
        pass
    for c in (r"C:\Users\c\AppData\Local\Programs\Python\Python313\Lib\site-packages\certifi\cacert.pem",
              "/etc/ssl/certs/ca-certificates.crt"):
        if os.path.exists(c):
            return c
    raise SystemExit("找不到证书库，请先 pip install certifi")


def split_pems(text):
    blocks, cur, inside = [], [], False
    for line in text.splitlines():
        if line.startswith("-----BEGIN CERTIFICATE-----"):
            inside, cur = True, [line]
        elif line.startswith("-----END CERTIFICATE-----"):
            cur.append(line)
            blocks.append("\n".join(cur))
            inside = False
        elif inside:
            cur.append(line)
    return blocks


def sha256_fp(pem):
    b64 = "".join(l for l in pem.splitlines() if not l.startswith("-----"))
    h = hashlib.sha256(base64.b64decode(b64)).hexdigest().upper()
    return ":".join(h[i:i + 2] for i in range(0, len(h), 2))


def read_validity(pem):
    """Best-effort read of notAfter; failure is non-fatal (just one less comment line)."""
    try:
        import ssl
    except ImportError:
        return None
    try:
        # Python 3.11+ offers no direct PEM parser, so this stays a coarse check
        # left to manual review upstream.
        return None
    except Exception:
        return None


def main():
    bundle = find_bundle()
    print("证书库：%s" % bundle)
    with open(bundle, "r", encoding="utf-8", errors="replace") as f:
        blocks = split_pems(f.read())

    hit = None
    for pem in blocks:
        if sha256_fp(pem) == EXPECT_SHA256:
            hit = pem
            break

    if hit is None:
        raise SystemExit("证书库里找不到指纹匹配的 ISRG Root X1，已中止")

    print("找到 %s，指纹校验通过" % LABEL)

    header = """#ifndef CERTS_H_
#define CERTS_H_

// ISRG Root X1 (Let's Encrypt)
// SHA-256 fingerprint:
//   %s
// Purpose: Open-Meteo runs over HTTPS and validates the server certificate
//          chain via setCACert().
//          Only the root is pinned, so intermediate rotations (e.g. the 2025
//          switch to YR1) require no code change.
// This file is generated by tools/get_isrg_x1.py - do not edit by hand.
// Re-run that script once the certificate expires (around 2035) to refresh it.

static const char ISRG_ROOT_X1_PEM[] = R"PEM(%s)PEM";

#endif /* CERTS_H_ */
""" % (EXPECT_SHA256, hit)

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(header)

    print("已写入 %s（PEM 共 %d 字节）" % (OUT, len(hit)))


if __name__ == "__main__":
    main()
